const assert=require('node:assert/strict');
const {findLedge,climbPosition}=require('../public/climb-rules.js');
const crate={minX:1,maxX:4,minY:0,maxY:1.5,minZ:-2,maxZ:2};
const at={x:0.2,y:0,z:0};
const front={x:1,z:0};
const ledge=findLedge([crate],at,front);
assert.ok(ledge,'front-facing reachable crate must be climbable');
assert.equal(ledge.landing.y,1.5);
assert.ok(ledge.landing.x>crate.minX && ledge.landing.x<crate.maxX);
assert.equal(findLedge([crate],at,{x:-1,z:0}),null,'must not climb behind the player');
assert.equal(findLedge([crate],{x:-5,y:0,z:0},front),null,'far ledges are not reachable');
assert.equal(findLedge([{...crate,maxY:5}],at,front),null,'high walls cannot be climbed');
assert.equal(findLedge([{...crate,maxY:.2}],at,front),null,'tiny steps do not trigger climbing');
assert.equal(findLedge([{...crate,minZ:4,maxZ:6}],at,front),null,'sideways ledges are not reachable');
assert.equal(findLedge([crate,{minX:1.5,maxX:4,minZ:-2,maxZ:2,minY:1.51,maxY:4}],at,front),null,'blocked landing rejected');
const start={x:0,y:0,z:0},end={x:2,y:1.5,z:0};
assert.deepEqual(climbPosition(start,end,0),start);
const finish=climbPosition(start,end,1);
assert.ok(Math.abs(finish.x-2)<1e-8&&Math.abs(finish.y-1.5)<1e-8);
assert.ok(climbPosition(start,end,.5).y>.75,'mantle provides vertical arc');
console.log('Climbing rules: 9 checks passed');
