const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const THREE=require('../public/vendor/three-r128.min.js');
const context={THREE,window:{}};
assert(fs.existsSync('public/operator-avatar.js'),'The approved operator must be available to the game');
vm.runInNewContext(fs.readFileSync('public/operator-motion.js','utf8'),context);
vm.runInNewContext(fs.readFileSync('public/operator-avatar.js','utf8'),context);
const a=new context.window.OperatorAvatar();
assert(a.group instanceof THREE.Group);assert(a.group.getObjectById(a.gun.id),'Weapon mount belongs to the approved rig');
for(let i=0;i<60;i++)a.update(1/60,{speed:3.8,grounded:true,armed:true});
assert(a.speed>3.7);assert(a.aimBlend>.99);const knee=a.legs[0].knee.rotation.x;
a.update(1/60,{speed:3.8,grounded:false,armed:true});assert.equal(a.wasGrounded,false,'Airborne state reaches the approved rig');
assert.notEqual(a.legs[0].knee.rotation.x,knee);
for(let i=0;i<120;i++)a.update(1/60,{speed:0,grounded:true,armed:false});assert(a.speed<.001);assert(a.aimBlend<.001);
a.group.updateMatrixWorld(true);a.group.traverse(o=>assert(o.matrixWorld.elements.every(Number.isFinite)));
const bounds=new THREE.Box3().setFromObject(a.group);assert(bounds.max.y-bounds.min.y>1.65&&bounds.max.y-bounds.min.y<1.95);assert(bounds.min.y>-.04);
console.log('Operator: mount, run, armed blending, jump, idle, finite transforms and height pass');
const standingTop=a.bones[5].getWorldPosition(new THREE.Vector3()).y;
for(let i=0;i<90;i++)a.update(1/60,{speed:0,grounded:true,armed:true,crouching:true});
assert(a.crouchBlend>.99,'Crouch must settle smoothly');a.group.updateMatrixWorld(true);
const crouchedBounds=new THREE.Box3().setFromObject(a.group);
assert(a.bones[5].getWorldPosition(new THREE.Vector3()).y<standingTop-.25,'Crouching must lower the real silhouette');assert(crouchedBounds.min.y>-.04,'Feet must remain above the ground');assert(a.aimBlend>.99,'Aiming must remain available while crouched');
for(let i=0;i<90;i++)a.update(1/60,{speed:1.8,grounded:true,crouching:true});
assert(a.crouchBlend>.99,'Crouch walking must retain its posture');assert(a.legs.every(l=>Math.abs(l.knee.rotation.x)>.4),'Crouch walking must keep knees bent');
for(let i=0;i<90;i++)a.update(1/60,{speed:0,grounded:true,crouching:false});assert(a.crouchBlend<.001,'Release must restore standing');
console.log('Crouch: silhouette, feet, aiming, crouch walking and release pass');
